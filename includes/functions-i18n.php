if (!function_exists('wpo_n_ru')) {
    /**
     * Русские падежи счётчика («1 файл / 2 файла / 5 файлов») без MO-перевода.
     *
     * _n() без перевода сайта выбирает форму по английскому правилу (n != 1),
     * а три русские строки в _n() передавать нельзя: третий аргумент — число.
     * Поэтому форма считается здесь; каждая строка остаётся переводимой (__()).
     */
    function wpo_n_ru(int $n, string $one, string $few, string $many): string
    {
        $m10 = abs($n) % 10;
        $m100 = abs($n) % 100;
        if ($m10 === 1 && $m100 !== 11) {
            return $one;
        }
        if ($m10 >= 2 && $m10 <= 4 && ($m100 < 12 || $m100 > 14)) {
            return $few;
        }
        return $many;
    }
}
